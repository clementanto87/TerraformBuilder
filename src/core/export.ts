/**
 * A three-stage pipeline: validate, plan, apply.
 *
 * The plan is published as an artifact and the apply consumes that exact
 * plan, so what a reviewer approves is what gets applied. Approvals are
 * attached to the Azure DevOps environment rather than encoded here.
 */
export function azurePipeline(options: PipelineOptions, backend: BackendConfig): string {
  const config = backend.config ?? {};

  // Held unindented; each call site indents them to its own depth.
  const backendInputs =
    backend.type === 'azurerm'
      ? [
          `backendServiceArm: '${options.serviceConnection}'`,
          `backendAzureRmResourceGroupName: '${config.resource_group_name ?? ''}'`,
          `backendAzureRmStorageAccountName: '${config.storage_account_name ?? ''}'`,
          `backendAzureRmContainerName: '${config.container_name ?? ''}'`,
          `backendAzureRmKey: '${config.key ?? ''}'`,
        ]
      : [];

  const init = (indent: string) =>
    [
      `${indent}- task: TerraformTaskV4@4`,
      `${indent}  displayName: Terraform init`,
      `${indent}  inputs:`,
      `${indent}    provider: azurerm`,
      `${indent}    command: init`,
      `${indent}    workingDirectory: $(workingDirectory)`,
      // Backend settings are further inputs, so they sit at the same depth.
      ...backendInputs.map((line) => `${indent}    ${line}`),
    ].join('\n');

  const installer = (indent: string) =>
    [
      `${indent}- task: TerraformInstaller@1`,
      `${indent}  displayName: Install Terraform $(terraformVersion)`,
      `${indent}  inputs:`,
      `${indent}    terraformVersion: $(terraformVersion)`,
    ].join('\n');

  return `# Generated by Terraform Builder.
#
# Prerequisites in Azure DevOps:
#   1. An ARM service connection named '${options.serviceConnection}' with rights
#      on the target subscription and on the state storage account.
#   2. An environment named '${options.environment}' carrying the approval checks
#      that gate the apply stage.
#   3. The Terraform extension by Microsoft DevLabs installed in the organisation.

trigger:
  branches:
    include:
      - ${options.defaultBranch}
  paths:
    include:
      - ${options.workingDirectory}/**

pr:
  branches:
    include:
      - ${options.defaultBranch}
  paths:
    include:
      - ${options.workingDirectory}/**

pool:
  vmImage: ubuntu-latest

variables:
  terraformVersion: '${options.terraformVersion}'
  workingDirectory: '$(System.DefaultWorkingDirectory)/${options.workingDirectory}'

stages:
  - stage: validate
    displayName: Validate
    jobs:
      - job: validate
        displayName: Format and validate
        steps:
${installer('          ')}

          - script: terraform fmt -check -recursive
            displayName: Check formatting
            workingDirectory: $(workingDirectory)

${init('          ')}

          - task: TerraformTaskV4@4
            displayName: Terraform validate
            inputs:
              provider: azurerm
              command: validate
              workingDirectory: $(workingDirectory)

  - stage: plan
    displayName: Plan
    dependsOn: validate
    condition: succeeded()
    jobs:
      - job: plan
        displayName: Terraform plan
        steps:
${installer('          ')}

${init('          ')}

          - task: TerraformTaskV4@4
            displayName: Terraform plan
            inputs:
              provider: azurerm
              command: plan
              workingDirectory: $(workingDirectory)
              environmentServiceNameAzureRM: '${options.serviceConnection}'
              commandOptions: '-input=false -out=$(Build.ArtifactStagingDirectory)/tfplan'

          # The apply stage consumes this exact plan, so what is reviewed is
          # what is applied.
          - publish: $(Build.ArtifactStagingDirectory)/tfplan
            artifact: tfplan
            displayName: Publish plan

  - stage: apply
    displayName: Apply
    dependsOn: plan
    condition: and(succeeded(), eq(variables['Build.SourceBranch'], 'refs/heads/${options.defaultBranch}'))
    jobs:
      - deployment: apply
        displayName: Terraform apply
        environment: '${options.environment}'
        strategy:
          runOnce:
            deploy:
              steps:
                - checkout: self

${installer('                ')}

                - download: current
                  artifact: tfplan
                  displayName: Download plan

${init('                ')}

                - task: TerraformTaskV4@4
                  displayName: Terraform apply
                  inputs:
                    provider: azurerm
                    command: apply
                    workingDirectory: $(workingDirectory)
                    environmentServiceNameAzureRM: '${options.serviceConnection}'
                    commandOptions: '-input=false $(Pipeline.Workspace)/tfplan/tfplan'
`;
}

