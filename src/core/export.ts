function readme(design: Design, options: ExportOptions): string {
  const config = options.backend.config ?? {};
  return `# ${design.name}

Generated by Terraform Builder. Edit freely — this is ordinary Terraform.

## Layout

| File | Purpose |
| --- | --- |
| \`providers.tf\` | Provider requirements and remote state backend |
| \`main.tf\` | The resources themselves |
| \`variables.tf\` | Inputs, including anything marked sensitive |
| \`outputs.tf\` | Resource ids for downstream stacks |

## Running it locally

\`\`\`bash
terraform init
terraform plan
\`\`\`

Sensitive values are declared as variables and are deliberately absent from the
code. Supply them at plan time, from a \`*.auto.tfvars\` file that is not
committed, or from pipeline variables marked secret.

## Running it in Azure DevOps

\`azure-pipelines.yml\` defines validate → plan → apply.

1. Commit this folder to \`${options.pipeline.workingDirectory}/\` in your repository.
2. Create an ARM service connection named \`${options.pipeline.serviceConnection}\`.
3. Create an environment named \`${options.pipeline.environment}\` and attach approvals to it.
4. Install the Terraform extension by Microsoft DevLabs in your organisation.
5. Create a pipeline pointing at \`azure-pipelines.yml\`.

State is kept in the \`${config.container_name ?? 'tfstate'}\` container of storage
account \`${config.storage_account_name ?? ''}\` under the key
\`${config.key ?? ''}\`. Create that storage account before the first run — the
backend cannot bootstrap itself.
`;
}

const GITIGNORE = `.terraform/
*.tfstate
*.tfstate.*
*.tfvars
!*.auto.tfvars.example
crash.log
override.tf
override.tf.json
`;

/** Assembles every file the export contains. */
export function buildBundle(
  design: Design,
  pack: ProviderPack,
  options: ExportOptions,
): GeneratedFile[] {
  const { files } = generate(design, pack, { backend: options.backend });
  const bundle = [...files];

  if (options.includePipeline) {
    bundle.push({
      path: 'azure-pipelines.yml',
      contents: azurePipeline(options.pipeline, options.backend),
    });
  }
  if (options.includeReadme) {
    bundle.push({ path: 'README.md', contents: readme(design, options) });
  }
  bundle.push({ path: '.gitignore', contents: GITIGNORE });

  // The design itself travels with the code, so the diagram can be reopened
  // and edited later rather than reverse-engineered.
  bundle.push({
    path: '.terraform-builder.json',
    contents: `${JSON.stringify(design, null, 2)}\n`,
  });

  return bundle;
}

/** Slug suitable for a file name. */
export const slugify = (name: string): string =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'infrastructure';

export async function downloadZip(files: GeneratedFile[], name: string): Promise<void> {
  const zip = new JSZip();
  for (const file of files) zip.file(file.path, file.contents);

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${slugify(name)}.zip`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

/** Downloads a single file, for the "just give me main.tf" case. */
export function downloadFile(file: GeneratedFile): void {
  const blob = new Blob([file.contents], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = file.path;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
