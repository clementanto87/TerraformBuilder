/**
 * Export.
 *
 * Produces a Terraform module laid out the way a repository expects it, plus
 * an Azure Pipelines definition that runs it. The pipeline is the deliverable
 * the design is actually for: nothing here runs Terraform in the browser or
 * asks for a credential.
 */

import JSZip from 'jszip';
import { generate, type BackendConfig, type GeneratedFile } from './generate';
import type { Design, ProviderPack } from './types';

export interface PipelineOptions {
  /** Azure DevOps service connection (an ARM service principal). */
  serviceConnection: string;
  /** Folder the module lands in, relative to the repository root. */
  workingDirectory: string;
  /** Azure DevOps environment gating the apply stage, where approvals live. */
  environment: string;
  terraformVersion: string;
  /** Branch that is allowed to apply. */
  defaultBranch: string;
}

export interface ExportOptions {
  backend: BackendConfig;
  pipeline: PipelineOptions;
  includePipeline: boolean;
  includeReadme: boolean;
}

export const defaultPipelineOptions = (): PipelineOptions => ({
  serviceConnection: 'azure-terraform',
  workingDirectory: 'infra',
  environment: 'production',
  terraformVersion: '1.9.5',
  defaultBranch: 'main',
});

export const defaultBackend = (): BackendConfig => ({
  type: 'azurerm',
  config: {
    resource_group_name: 'rg-terraform-state',
    storage_account_name: 'sttfstate',
    container_name: 'tfstate',
    key: 'infrastructure.tfstate',
  },
});

